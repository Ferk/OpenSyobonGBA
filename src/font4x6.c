uint8_t font4x6_row(char ch, uint8_t row)
{
    if (ch >= 'a' && ch <= 'z') {
        ch = (char)(ch - 'a' + 'A');
    }

    if (row >= FONT4X6_HEIGHT ||
        ch < FONT4X6_FIRST_CHAR || ch > FONT4X6_LAST_CHAR) {
        return 0;
    }

    return font4x6_data[(uint8_t)ch - FONT4X6_FIRST_CHAR][row];
}
